/**
 * POST /api/v1/auth/avatar   (multipart/form-data, field: 'avatar')
 * Replace the signed-in user's profile picture.
 */
const uploadAvatar = async (req, res, next) => {
  try {
    // Staff (super_admin / admin / developer) use a fixed role emblem and are
    // not allowed a personal photo. This is enforced here rather than only in
    // the UI, because hiding a button is not authorisation - a direct API call
    // would otherwise still succeed.
    const STAFF_ROLES = ['super_admin', 'admin', 'developer'];

    const [roleRows] = await pool.query(
      'SELECT role, avatar_url FROM users WHERE id = $1',
      [req.user.id]
    );

    if (roleRows.length === 0) {
      return res.status(404).json({ success: false, message: 'User profile not found' });
    }

    if (STAFF_ROLES.includes(roleRows[0].role)) {
      return res.status(403).json({
        success: false,
        message: 'Staff accounts use a fixed role emblem and cannot set a profile picture.'
      });
    }

    if (!req.file) {
      return res.status(400).json({
        success: false,
        message: 'No image was uploaded. Send a file in the "avatar" field.'
      });
    }

    const userId = req.user.id;

    // Content check. multer has already validated the declared MIME type and
    // the extension, but both are attacker-controlled, so confirm the actual
    // bytes really are an image before anything is stored anywhere.
    const ext = path.extname(req.file.originalname).toLowerCase();
    if (!verifyImageBuffer(req.file.buffer, ext)) {
      return res.status(400).json({
        success: false,
        message:
          'That file is not a valid image. Its contents do not match its file extension.'
      });
    }

    // Cloudinary when CLOUDINARY_URL is configured (production/Vercel),
    // local disk otherwise (development).
    const stored = await saveAvatar(req.file.buffer, ext, userId);
    const avatarUrl = stored.url;

    // Grab the previous value so the old file can be cleaned up once the new
    // one is safely recorded.
    const [existing] = await pool.query('SELECT avatar_url FROM users WHERE id = $1', [userId]);
    const previousAvatar = existing[0]?.avatar_url;

    try {
      await pool.query('UPDATE users SET avatar_url = $1 WHERE id = $2', [avatarUrl, userId]);
    } catch (updateError) {
      // Never leave an orphaned file behind when the row could not be saved.
      removeAvatarFile(avatarUrl);
      throw updateError;
    }

    // Best-effort cleanup - never fail the request because of it.
    removeAvatarFile(previousAvatar);

    res.status(200).json({
      success: true,
      message: 'Profile picture updated',
      avatar_url: avatarUrl
    });
  } catch (error) {
    next(error);
  }
};

/**
 * DELETE /api/v1/auth/avatar
 * Remove the profile picture and fall back to the generated avatar.
 */
const deleteAvatar = async (req, res, next) => {
  try {
    const userId = req.user.id;

    const [existing] = await pool.query('SELECT role, avatar_url FROM users WHERE id = $1', [userId]);
    const currentAvatar = existing[0]?.avatar_url;

    // Same rule as upload - staff have no personal photo to remove.
    if (['super_admin', 'admin', 'developer'].includes(existing[0]?.role)) {
      return res.status(403).json({
        success: false,
        message: 'Staff accounts use a fixed role emblem and have no profile picture.'
      });
    }

    await pool.query('UPDATE users SET avatar_url = NULL WHERE id = $1', [userId]);

    removeAvatarFile(currentAvatar);

    res.status(200).json({
      success: true,
      message: 'Profile picture removed',
      avatar_url: null
    });
  } catch (error) {
    next(error);
  }
};

/**
 * PUT /api/v1/auth/me
 * Update the signed-in user's own name. Email changes go through the
 * verified flow (requestEmailChange / verifyEmailChange) so a stolen session
 * cannot silently move an account to an attacker-controlled address.
 */
const updateProfile = async (req, res, next) => {
  try {
    const userId = req.user.id;
    const name = typeof req.body?.name === 'string' ? req.body.name.trim() : undefined;

    if (name === undefined) {
      return res.status(400).json({
        success: false,
        message: 'Validation Error: provide a name to update'
      });
    }

    if (name === '' || name.length > 100) {
      return res.status(400).json({
        success: false,
        message: 'Validation Error: name must be 1-100 characters'
      });
    }

    const [updated] = await pool.query(
      'UPDATE users SET name = $1 WHERE id = $2 RETURNING id, name, email, role, avatar_url, status',
      [name, userId]
    );

    if (updated.length === 0) {
      return res.status(404).json({ success: false, message: 'User not found' });
    }

    const user = updated[0];

    // Re-issue the token so the session reflects the new name without a
    // forced re-login. The client stores it and the AuthContext refresh picks
    // up the rest from /auth/me.
    const token = jwt.sign(
      { id: user.id, email: user.email, role: user.role, name: user.name },
      process.env.JWT_SECRET,
      { expiresIn: process.env.JWT_EXPIRES_IN || '7d' }
    );

    res.status(200).json({
      success: true,
      message: 'Profile updated successfully',
      token,
      user
    });

  } catch (error) {
    next(error);
  }
};

/**
 * POST /api/v1/auth/me/email/request-change
 * Send a 6-digit verification code to the NEW email address. The account's
 * email is NOT changed yet - only after verifyEmailChange succeeds.
 */
const requestEmailChange = async (req, res, next) => {
  try {
    const userId = req.user.id;
    const newEmail = typeof req.body?.email === 'string' ? req.body.email.trim().toLowerCase() : '';

    if (!newEmail || newEmail.length > 150 || !/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(newEmail)) {
      return res.status(400).json({
        success: false,
        message: 'Validation Error: a valid email address is required'
      });
    }

    // Make sure the target address is not already taken by someone else.
    const [existing] = await pool.query(
      'SELECT id FROM users WHERE email = $1 AND id <> $2',
      [newEmail, userId]
    );
    if (existing.length > 0) {
      return res.status(409).json({
        success: false,
        message: 'Validation Error: that email is already in use'
      });
    }

    // The verification table is created on demand, mirroring sendOtp, so this
    // works even for accounts that never used OTP sign-up.
    await pool.query(`
      CREATE TABLE IF NOT EXISTS email_verifications (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email VARCHAR(150) NOT NULL,
        otp_code VARCHAR(10) NOT NULL,
        expires_at TIMESTAMPTZ NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);
    await pool.query('CREATE INDEX IF NOT EXISTS idx_ev_email ON email_verifications (email)');
    await pool.query('CREATE INDEX IF NOT EXISTS idx_ev_code ON email_verifications (otp_code)');

    const otpCode = Math.floor(100000 + Math.random() * 900000).toString();
    await pool.query('DELETE FROM email_verifications WHERE email = $1', [newEmail]);
    await pool.query(
      'INSERT INTO email_verifications (email, otp_code, expires_at) VALUES ($1, $2, NOW() + INTERVAL \'10 minutes\') RETURNING id',
      [newEmail, otpCode]
    );

    const { sendOtpEmail } = require('../utils/emailService');
    const emailResult = await sendOtpEmail(newEmail, otpCode);
    if (!emailResult.sent) {
      return res.status(502).json({
        success: false,
        message: 'We could not send the verification email. Check that address, then try again in a minute.'
      });
    }

    res.status(200).json({
      success: true,
      message: `A 6-digit verification code has been sent to ${newEmail}.`
    });

  } catch (error) {
    next(error);
  }
};

/**
 * POST /api/v1/auth/me/email/verify-change
 * Verify the code sent to the new address and, on success, move the account
 * to that address. Re-issues the session token afterwards.
 */
const verifyEmailChange = async (req, res, next) => {
  try {
    const userId = req.user.id;
    const newEmail = typeof req.body?.email === 'string' ? req.body.email.trim().toLowerCase() : '';
    const otp = typeof req.body?.otp === 'string' ? req.body.otp.trim() : '';

    if (!newEmail || !otp) {
      return res.status(400).json({
        success: false,
        message: 'Validation Error: email and verification code are required'
      });
    }

    const [rows] = await pool.query(
      'SELECT id FROM email_verifications WHERE email = $1 AND otp_code = $2 AND expires_at > NOW()',
      [newEmail, otp]
    );
    if (rows.length === 0) {
      return res.status(400).json({
        success: false,
        message: 'Validation Error: invalid or expired verification code'
      });
    }

    // Re-check uniqueness in case someone else grabbed the address in the
    // meantime.
    const [existing] = await pool.query(
      'SELECT id FROM users WHERE email = $1 AND id <> $2',
      [newEmail, userId]
    );
    if (existing.length > 0) {
      return res.status(409).json({
        success: false,
        message: 'Validation Error: that email is already in use'
      });
    }

    const [updated] = await pool.query(
      'UPDATE users SET email = $1 WHERE id = $2 RETURNING id, name, email, role, avatar_url, status',
      [newEmail, userId]
    );

    if (updated.length === 0) {
      return res.status(404).json({ success: false, message: 'User not found' });
    }

    const user = updated[0];

    // Consume the code so it cannot be reused.
    await pool.query('DELETE FROM email_verifications WHERE email = $1', [newEmail]);

    const token = jwt.sign(
      { id: user.id, email: user.email, role: user.role, name: user.name },
      process.env.JWT_SECRET,
      { expiresIn: process.env.JWT_EXPIRES_IN || '7d' }
    );

    res.status(200).json({
      success: true,
      message: 'Email updated successfully',
      token,
      user
    });

  } catch (error) {
    next(error);
  }
};

